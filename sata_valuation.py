@jit(nopython=True, parallel=False)
def calculate_npv_matrix_multiplication(cash_flows: np.ndarray, discount_factors: np.ndarray) -> float:
    """Calculate NPV using matrix multiplication with precomputed discount factors.

    Parameters:
    - cash_flows: Array of cash flows for each month (shape: n_months)
    - discount_factors: Precomputed discount factors for each month (shape: n_months)
                      where discount_factors[t] = (1 + r)^(t+1)

    Returns:
    - NPV value
    """
    return np.sum(cash_flows / discount_factors)


