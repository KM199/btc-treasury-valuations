def run_baseline_analysis(baseline_price_paths: np.ndarray, config_dict: Dict[str, Any],
                         num_workers: int) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Run baseline scenario dividend sustainability analysis with optimized chunking."""

    print("\n" + "="*70)
    print("BASELINE SCENARIO: DIVIDEND SUSTAINABILITY ANALYSIS")
    print("="*70)
    print(f"Calculating dividend sustainability for {config_dict['num_simulations']:,} simulations...")

    # Optimized chunking: larger chunks reduce overhead (80/20 optimization)
    chunk_size = max(500, config_dict['num_simulations'] // (num_workers * 2))  # Fewer, larger chunks
    chunks = []
    for i in range(0, config_dict['num_simulations'], chunk_size):
        chunk_param = (i, min(i + chunk_size, config_dict['num_simulations']))
        chunks.append(('baseline_chunk', chunk_param, baseline_price_paths, config_dict))

    # Execute in parallel with fallback
    baseline_results = execute_parallel_with_fallback(
        simulate_unified_worker, chunks, num_workers, "simulation chunks"
    )

    # Combine results efficiently - direct array operations (faster than list comprehensions)
    months_dividends_paid = np.concatenate([r.months_dividends_paid for r in baseline_results])
    final_bitcoin_holdings = np.concatenate([r.final_bitcoin_holdings for r in baseline_results])
    final_cash_reserve = np.concatenate([r.final_cash_reserve for r in baseline_results])
    accumulated_unpaid_dividends_final = np.concatenate([r.accumulated_unpaid_dividends_final for r in baseline_results])
    npvs = np.concatenate([r.npvs for r in baseline_results])

    # Immediate cleanup to free memory
    del baseline_results
    gc.collect()

    print(f"\n✓ Baseline scenario complete!")
    full_payment_mask = months_dividends_paid == config_dict['total_months']
    print(f"  Average months paid: {months_dividends_paid.mean():.1f}")
    print(f"  Median months paid: {np.median(months_dividends_paid):.1f}")
    print(f"  Average NPV per share: ${npvs.mean():,.2f}")
    print(f"  Simulations that paid full period: {full_payment_mask.sum():,} ({full_payment_mask.mean()*100:.1f}%)")

    return months_dividends_paid, final_bitcoin_holdings, final_cash_reserve, accumulated_unpaid_dividends_final, npvs


