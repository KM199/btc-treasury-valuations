def run_scenario_analysis(scenarios: List[Dict], config_dict: Dict[str, Any],
                         num_workers: int) -> np.ndarray:
    """Execute multi-scenario NPV analysis across different Bitcoin starting price assumptions, calculating valuation impact for each scenario."""

    if len(scenarios) <= 1:
        return np.array([], dtype=RESULT_DTYPE)

    # Find the baseline scenario (starting_price_pct closest to 0)
    baseline_scenario_idx = min(range(len(scenarios)),
                               key=lambda i: abs(scenarios[i]['starting_price_pct']))

    # Filter out the baseline scenario (starting_price_pct closest to 0)
    non_baseline_scenarios = []
    non_baseline_indices = []
    for i, scenario in enumerate(scenarios):
        if abs(scenario['starting_price_pct']) > 0.001:  # Not the baseline
            non_baseline_scenarios.append(scenario)
            non_baseline_indices.append(i)

    if len(non_baseline_scenarios) == 0:
        return np.array([], dtype=RESULT_DTYPE)

    print("\n" + "="*70)
    print("MULTI-SCENARIO NPV ANALYSIS")
    print("="*70)
    print(f"Calculating NPV for {len(non_baseline_scenarios)} scenarios (excluding redundant baseline)...")

    # Create tasks for parallel scenario processing (only non-baseline scenarios)
    scenario_args = [('scenario', {'idx': original_idx, **non_baseline_scenarios[i]}, None, config_dict)
                    for i, original_idx in enumerate(non_baseline_indices)]

    # Execute in parallel with fallback
    scenario_results = execute_parallel_with_fallback(
        simulate_unified_worker, scenario_args, num_workers, "scenarios"
    )

    # Add baseline result (which was already calculated)
    # Get baseline statistics from config_dict
    baseline_npv_mean = config_dict.get('baseline_npv_per_share_mean', 0)
    baseline_npv_median = config_dict.get('baseline_npv_per_share_median', 0)
    baseline_npv_std = config_dict.get('baseline_npv_per_share_std', 0)
    baseline_months_mean = config_dict.get('baseline_months_paid_mean', 0)

    baseline_result = create_scenario_result(
        scenario_idx=baseline_scenario_idx,
        starting_price_pct=scenarios[baseline_scenario_idx]['starting_price_pct'],
        starting_price=scenarios[baseline_scenario_idx]['starting_price'],
        mean_npv_per_share=baseline_npv_mean,
        median_npv_per_share=baseline_npv_median,
        mean_months_paid=baseline_months_mean,
        std_npv_per_share=baseline_npv_std,
        min_npv_per_share=baseline_npv_mean,  # For baseline scenario, min=max=mean
        max_npv_per_share=baseline_npv_mean
    )

    # Convert list of structured arrays to single concatenated array
    if len(scenario_results) > 0:
        all_results = np.concatenate(scenario_results + [baseline_result])
    else:
        all_results = baseline_result

    # Sort by scenario index
    sort_indices = np.argsort(all_results['scenario_idx'])
    all_results = all_results[sort_indices]

    print(f"\n✓ Multi-scenario analysis complete! (including baseline)")
    return all_results


