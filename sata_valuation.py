def execute_parallel_with_fallback(worker_function: callable, tasks: List[Any],
                                 num_workers: int, description: str = "tasks") -> List[Any]:
    """Execute tasks in parallel with automatic fallback to sequential processing.

    Args:
        worker_function: Function to execute for each task
        tasks: List of task arguments
        num_workers: Number of worker processes to use
        description: Description for progress messages

    Returns:
        List of results from worker function
    """
    results = []

    try:
        with ProcessPoolExecutor(max_workers=num_workers) as executor:
            futures = {executor.submit(worker_function, task): task for task in tasks}
            for future in as_completed(futures):
                results.append(future.result())
                print(f"  Progress: {len(results)}/{len(tasks)} {description} completed...")

    except (OSError, PermissionError) as e:
        print(f"  Multiprocessing failed ({e}), falling back to sequential processing...")
        # Fallback to sequential processing
        for task in tasks:
            result = worker_function(task)
            results.append(result)
            print(f"  Progress: {len(results)}/{len(tasks)} {description} completed...")

    return results


