def simulate_single_dividend_path(initial_cash_reserve: float, initial_bitcoin_holdings: float,
                                 price_path: np.ndarray, config: Dict[str, Any],
                                 threshold_multiplier: Optional[float] = None,
                                 enable_early_termination: bool = True) -> Tuple[int, float, float, float, np.ndarray]:
    """Core dividend simulation logic for a single simulation path with incremental NPV calculation.

    Parameters:
    - initial_cash_reserve: Starting cash reserve
    - initial_bitcoin_holdings: Starting Bitcoin holdings
    - price_path: Array of monthly Bitcoin prices for this simulation
    - config: Configuration dict with simulation parameters
    - threshold_multiplier: Optional override for threshold calculation (default uses config value)

    Returns:
    - months_paid: Number of months dividends were paid
    - final_bitcoin_holdings: Bitcoin holdings at simulation end
    - final_cash_reserve: Cash reserve at simulation end
    - accumulated_unpaid_dividends: Final accumulated unpaid dividends
    - cash_flows: Array of cash flows for each month (for matrix multiplication NPV)
    """
    # Extract config values
    TOTAL_MONTHS = config['total_months']
    SATA_MONTHLY_DIVIDEND_TOTAL = config['sata_monthly_dividend_total']
    TOTAL_PAR_VALUE = config['total_par_value']
    DIVIDEND_SUSPENSION_THRESHOLD_MULTIPLIER = config['dividend_suspension_threshold_multiplier']
    COMPOUNDED_DIVIDEND_START_RATE = config['compounded_dividend_start_rate']
    COMPOUNDED_DIVIDEND_INCREMENT = config['compounded_dividend_increment']
    COMPOUNDED_DIVIDEND_MAX_RATE = config['compounded_dividend_max_rate']
    MONTHLY_DISCOUNT_RATE = config['monthly_discount_rate']

    # Use provided threshold_multiplier or default from config
    threshold_mult = threshold_multiplier if threshold_multiplier is not None else DIVIDEND_SUSPENSION_THRESHOLD_MULTIPLIER

    # Pre-calculate threshold value (constant throughout simulation)
    threshold_value = TOTAL_PAR_VALUE * threshold_mult

    # Cache frequently used values to avoid repeated dictionary lookups
    monthly_dividend_total = SATA_MONTHLY_DIVIDEND_TOTAL
    compounded_start_rate = COMPOUNDED_DIVIDEND_START_RATE
    compounded_increment = COMPOUNDED_DIVIDEND_INCREMENT
    compounded_max_rate = COMPOUNDED_DIVIDEND_MAX_RATE

    # Discount factors now pre-computed in worker functions for matrix multiplication

    # Initialize simulation state
    cash_reserve = initial_cash_reserve
    bitcoin_holdings = initial_bitcoin_holdings
    months_paid = 0
    accumulated_unpaid_dividends = 0.0
    months_unpaid = 0
    cash_flows = np.zeros(TOTAL_MONTHS)  # Cash flows for each month

    consecutive_insolvent_months = 0

    # Simulate each month - this is the 80% bottleneck
    for month in range(TOTAL_MONTHS):
        btc_price = price_path[month]
        bitcoin_value = bitcoin_holdings * btc_price

        # Early termination check: if insolvent for 24+ consecutive months
        if enable_early_termination and bitcoin_holdings <= 0.001 and cash_reserve < monthly_dividend_total and consecutive_insolvent_months >= 24:
            break

        if bitcoin_value >= threshold_value:
            consecutive_insolvent_months = 0  # Reset counter when above threshold

            # Pay accumulated dividends first (ultra-streamlined)
            if accumulated_unpaid_dividends > 0:
                # Fast path: calculate total available resources
                total_available = cash_reserve + bitcoin_holdings * btc_price
                accumulated_payment = min(accumulated_unpaid_dividends, total_available)

                if accumulated_payment > 0:
                    # Optimized deduction: use cash first, then BTC
                    cash_used = min(accumulated_payment, cash_reserve)
                    btc_used = (accumulated_payment - cash_used) / btc_price

                    cash_reserve -= cash_used
                    bitcoin_holdings -= btc_used
                    cash_flows[month] += accumulated_payment  # Record cash flow

                    accumulated_unpaid_dividends -= accumulated_payment
                    months_unpaid = 0 if accumulated_unpaid_dividends <= 0 else months_unpaid

            # Pay regular dividend (ultra-streamlined)
            remaining_value = cash_reserve + bitcoin_holdings * btc_price
            if remaining_value >= monthly_dividend_total:
                # Optimized deduction: same logic as above
                cash_used = min(monthly_dividend_total, cash_reserve)
                btc_used = (monthly_dividend_total - cash_used) / btc_price

                cash_reserve -= cash_used
                bitcoin_holdings -= btc_used
                cash_flows[month] += monthly_dividend_total  # Record cash flow
                months_paid += 1

            elif accumulated_unpaid_dividends <= 0:
                # No payments possible - accumulate with compound rate
                months_unpaid += 1
                compounded_rate = min(compounded_start_rate + (months_unpaid * compounded_increment), compounded_max_rate)
                accumulated_unpaid_dividends += monthly_dividend_total * (1 + compounded_rate/12)
                consecutive_insolvent_months += 1
        else:
            # Bitcoin value below threshold - suspend dividend
            months_unpaid += 1
            compounded_rate = min(compounded_start_rate + (months_unpaid * compounded_increment), compounded_max_rate)
            accumulated_unpaid_dividends += monthly_dividend_total * (1 + compounded_rate/12)
            consecutive_insolvent_months += 1

    return months_paid, bitcoin_holdings, cash_reserve, accumulated_unpaid_dividends, cash_flows

def simulate_unified_worker(args: Tuple[str, Any, np.ndarray, Dict[str, Any]]) -> Any:
    """Unified worker function for all simulation types - eliminates massive code duplication."""
    worker_type, worker_param, price_paths, config = args

    discount_factors = config['discount_factors']

    # Handle different worker types and determine simulation range and array sizes
    if worker_type == 'baseline_chunk':
        sim_start, sim_end = worker_param
        simulation_range = range(sim_start, sim_end)
        array_size = sim_end - sim_start
    else:
        num_simulations = config['num_simulations']
        simulation_range = range(num_simulations)
        array_size = num_simulations

    # Initialize result arrays with correct size
    months_paid = np.zeros(array_size)
    npvs = np.zeros(array_size)
    npvs_per_share = np.zeros(array_size)
    accumulated_unpaid_final = np.zeros(array_size)

    # Configure simulation parameters and price paths based on worker type
    sim_kwargs = {}
    if worker_type == 'scenario':
        # For scenarios, extract price paths from scenario data
        price_paths = np.array(worker_param['price_paths'])
    elif worker_type == 'threshold':
        sim_kwargs['threshold_multiplier'] = worker_param
    elif worker_type == 'dividend_rate':
        # Create modified config for dividend rate sensitivity
        modified_config = config.copy()
        modified_config['sata_annual_dividend_rate'] = worker_param
        modified_config['sata_monthly_dividend_per_share'] = worker_param * config['sata_par_value'] / 12
        modified_config['sata_monthly_dividend_total'] = modified_config['sata_monthly_dividend_per_share'] * config['sata_shares_outstanding']
        sim_kwargs['config_override'] = modified_config
    elif worker_type == 'btc_credit':
        # Calculate BTC holdings for this credit ratio (adjusted BTC credit includes cash)
        # Formula: adjusted_btc_credit = (btc_holdings * btc_price + cash) / total_par_value
        # Rearranged: btc_holdings = (adjusted_btc_credit * total_par_value - cash) / btc_price
        target_total_value = worker_param * config['total_par_value']
        cash = config['initial_cash_reserve']
        required_btc_value = target_total_value - cash
        btc_holdings = max(0, required_btc_value / config['current_bitcoin_price'])
        modified_config = config.copy()
        modified_config['initial_bitcoin_holdings'] = btc_holdings
        sim_kwargs['config_override'] = modified_config

    # Run simulations
    for sim_idx, sim in enumerate(simulation_range):
        # Use shared dividend simulation function
        config_to_use = sim_kwargs.get('config_override', config)

        months, final_btc, final_cash, accumulated_unpaid, cash_flows = simulate_single_dividend_path(
            config_to_use['initial_cash_reserve'],
            config_to_use['initial_bitcoin_holdings'],
            price_paths[sim],
            config_to_use,
            threshold_multiplier=sim_kwargs.get('threshold_multiplier', config_to_use.get('dividend_suspension_threshold_multiplier')),
            enable_early_termination=config_to_use.get('enable_early_termination', True)
        )

        # Calculate NPV
        npv = calculate_npv_matrix_multiplication(cash_flows, discount_factors)

        # Store results
        months_paid[sim_idx] = months
        npvs[sim_idx] = npv
        npvs_per_share[sim_idx] = npv / config['sata_shares_outstanding']
        accumulated_unpaid_final[sim_idx] = accumulated_unpaid

    # Return appropriate result based on worker type
    if worker_type == 'baseline_chunk':
        sim_start, sim_end = worker_param
        return DividendSimulationResult(
            sim_start=sim_start,
            sim_end=sim_end,
            months_dividends_paid=months_paid,
            final_bitcoin_holdings=np.zeros(len(months_paid)),  # Not used in baseline
            final_cash_reserve=np.zeros(len(months_paid)),      # Not used in baseline
            accumulated_unpaid_dividends_final=accumulated_unpaid_final,
            npvs=npvs
        )
    elif worker_type == 'scenario':
        return create_scenario_result(
            scenario_idx=worker_param['idx'],
            starting_price_pct=worker_param['starting_price_pct'],
            starting_price=worker_param['starting_price'],
            mean_npv_per_share=npvs_per_share.mean(),
            median_npv_per_share=np.median(npvs_per_share),
            mean_months_paid=months_paid.mean(),
            std_npv_per_share=npvs_per_share.std(),
            min_npv_per_share=npvs_per_share.min(),
            max_npv_per_share=npvs_per_share.max()
        )
    elif worker_type == 'threshold':
        total_months = config['total_months']
        return create_sensitivity_threshold_result(
            threshold_multiplier=worker_param,
            threshold_value=config['total_par_value'] * worker_param,
            mean_npv_per_share=npvs_per_share.mean(),
            median_npv_per_share=np.median(npvs_per_share),
            mean_months_paid=months_paid.mean(),
            mean_accumulated_unpaid=accumulated_unpaid_final.mean(),
            std_npv_per_share=npvs_per_share.std()
        )
    elif worker_type == 'dividend_rate':
        baseline_rate = config['sata_annual_dividend_rate']
        total_months = config['total_months']
        return create_sensitivity_dividend_rate_result(
            dividend_rate=worker_param,
            dividend_rate_change_pct=((worker_param - baseline_rate) / baseline_rate) * 100,
            mean_npv_per_share=npvs_per_share.mean(),
            median_npv_per_share=np.median(npvs_per_share),
            mean_months_paid=months_paid.mean(),
            mean_accumulated_unpaid=accumulated_unpaid_final.mean(),
            std_npv_per_share=npvs_per_share.std()
        )
    elif worker_type == 'btc_credit':
        total_months = config['total_months']
        return create_sensitivity_btc_credit_result(
            btc_credit_ratio=worker_param,
            btc_holdings=btc_holdings,
            mean_npv_per_share=npvs_per_share.mean(),
            median_npv_per_share=np.median(npvs_per_share),
            mean_months_paid=months_paid.mean(),
            mean_accumulated_unpaid=accumulated_unpaid_final.mean(),
            std_npv_per_share=npvs_per_share.std(),
            npv_per_additional_btc=0.0  # Will be calculated later
        )




