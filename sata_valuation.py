class Configuration:
    """Centralized configuration management for SATA valuation model."""

    def __init__(self,
                 # SATA Parameters
                 sata_shares_outstanding: int = 2012700,
                 sata_annual_dividend_rate: float = 0.1225,
                 sata_par_value: float = 100.0,

                 # Treasury Parameters
                 initial_bitcoin_holdings: float = 7525.02,
                 initial_cash_reserve: float = 67600000.0,  # Default: ~67M (will be overridden by treasury_extracted_data.json if available)

                 # Financial Parameters
                 discount_rate_annual: float = 0.04159,

                 # Dividend Parameters
                 dividend_suspension_threshold_multiplier: float = 1.25,
                 compounded_dividend_start_rate: float = 0.1250,
                 compounded_dividend_increment: float = 0.0025,
                 compounded_dividend_max_rate: float = 0.20,

                 # Sensitivity Analysis
                 sensitivity_threshold_start: float = 0.0,
                 sensitivity_threshold_end: float = 2.0,
                 sensitivity_threshold_step: float = 0.25,

                 # BTC Credit Sensitivity Analysis - parameters calculated dynamically from current BTC credit ratio

                 # Performance Parameters
                 default_num_workers: Optional[int] = None,
                 chunk_size_multiplier: int = 8,

                 # Override from external data
                 **overrides):
        """Initialize configuration with defaults and optional overrides."""

        # SATA Parameters
        self.sata_shares_outstanding = overrides.get('sata_shares', sata_shares_outstanding)
        self.sata_annual_dividend_rate = overrides.get('sata_dividend_rate', sata_annual_dividend_rate)
        self.sata_par_value = sata_par_value

        # Treasury Parameters
        self.initial_bitcoin_holdings = overrides.get('bitcoin_holdings', initial_bitcoin_holdings)
        self.initial_cash_reserve = overrides.get('cash', initial_cash_reserve)

        # Financial Parameters
        self.discount_rate_annual = discount_rate_annual

        # Dividend Parameters
        self.dividend_suspension_threshold_multiplier = dividend_suspension_threshold_multiplier
        self.compounded_dividend_start_rate = compounded_dividend_start_rate
        self.compounded_dividend_increment = compounded_dividend_increment
        self.compounded_dividend_max_rate = compounded_dividend_max_rate

        # Sensitivity Analysis
        self.sensitivity_threshold_start = sensitivity_threshold_start
        self.sensitivity_threshold_end = sensitivity_threshold_end
        self.sensitivity_threshold_step = sensitivity_threshold_step

        # Dividend Rate Sensitivity Analysis
        self.dividend_rate_sensitivity_start_pct = -1.0   # -1.0% of baseline
        self.dividend_rate_sensitivity_end_pct = 1.0      # +1.0% of baseline
        self.dividend_rate_sensitivity_step_pct = 0.25    # 0.25% increments

        # BTC Credit Sensitivity Analysis - parameters calculated dynamically

        # Performance Parameters
        self.default_num_workers = default_num_workers
        self.chunk_size_multiplier = chunk_size_multiplier if chunk_size_multiplier is not None else 8
        self.enable_early_termination = True  # Enable early termination for insolvent simulations
        self.optimization_level = 2  # 0=baseline, 1=moderate, 2=aggressive optimizations

        # Computed properties
        self._computed_values = {}

    @property
    def sata_monthly_dividend_per_share(self) -> float:
        """Calculate monthly dividend per share."""
        return self.sata_annual_dividend_rate * self.sata_par_value / 12

    @property
    def sata_monthly_dividend_total(self) -> float:
        """Calculate total monthly dividend payment."""
        return self.sata_monthly_dividend_per_share * self.sata_shares_outstanding

    @property
    def total_par_value(self) -> float:
        """Calculate total par value of all shares."""
        return self.sata_shares_outstanding * self.sata_par_value

    @property
    def monthly_discount_rate(self) -> float:
        """Calculate monthly discount rate."""
        return (1 + self.discount_rate_annual) ** (1/12) - 1

    def get_sensitivity_thresholds(self) -> np.ndarray:
        """Get array of threshold multipliers for sensitivity analysis, excluding baseline."""
        all_thresholds = np.arange(self.sensitivity_threshold_start,
                                  self.sensitivity_threshold_end + self.sensitivity_threshold_step,
                                  self.sensitivity_threshold_step)
        # Exclude the baseline threshold multiplier to avoid redundant calculation
        return all_thresholds[np.abs(all_thresholds - self.dividend_suspension_threshold_multiplier) > 1e-6]

    def get_dividend_rate_sensitivity_values(self) -> np.ndarray:
        """Get array of dividend rates for dividend rate sensitivity analysis, excluding baseline."""
        start_rate = self.sata_annual_dividend_rate + (self.dividend_rate_sensitivity_start_pct / 100)
        end_rate = self.sata_annual_dividend_rate + (self.dividend_rate_sensitivity_end_pct / 100)
        step_rate = self.dividend_rate_sensitivity_step_pct / 100
        all_rates = np.arange(start_rate, end_rate + step_rate, step_rate)
        # Exclude the baseline dividend rate to avoid redundant calculation
        return all_rates[np.abs(all_rates - self.sata_annual_dividend_rate) > 1e-6]


    def to_dict(self) -> Dict[str, Any]:
        """Convert configuration to dictionary for worker functions."""
        return {
            'num_simulations': None,  # Set by price data
            'simulation_years': None,  # Set by price data
            'total_months': None,  # Set by price data
            'current_bitcoin_price': None,  # Set by price data
            'sata_shares_outstanding': self.sata_shares_outstanding,
            'sata_annual_dividend_rate': self.sata_annual_dividend_rate,
            'sata_par_value': self.sata_par_value,  # Add this line
            'sata_monthly_dividend_per_share': self.sata_monthly_dividend_per_share,
            'sata_monthly_dividend_total': self.sata_monthly_dividend_total,
            'initial_bitcoin_holdings': self.initial_bitcoin_holdings,
            'initial_cash_reserve': self.initial_cash_reserve,
            'total_par_value': self.total_par_value,
            'dividend_suspension_threshold_multiplier': self.dividend_suspension_threshold_multiplier,
            'compounded_dividend_start_rate': self.compounded_dividend_start_rate,
            'compounded_dividend_increment': self.compounded_dividend_increment,
            'compounded_dividend_max_rate': self.compounded_dividend_max_rate,
        'discount_rate_annual': self.discount_rate_annual,
        'monthly_discount_rate': self.monthly_discount_rate,
        'enable_early_termination': self.enable_early_termination
        }

    def validate(self) -> None:
        """Validate configuration parameters."""
        if self.sata_shares_outstanding <= 0:
            raise ValueError("SATA shares outstanding must be positive")
        if not (0 < self.sata_annual_dividend_rate <= 1):
            raise ValueError("SATA dividend rate must be between 0 and 1")
        if self.sata_par_value <= 0:
            raise ValueError("SATA par value must be positive")
        if self.initial_bitcoin_holdings < 0:
            raise ValueError("Initial Bitcoin holdings cannot be negative")
        if self.initial_cash_reserve < 0:
            raise ValueError("Initial cash reserve cannot be negative")
        if self.discount_rate_annual < 0:
            raise ValueError("Discount rate cannot be negative")
        if self.dividend_suspension_threshold_multiplier <= 0:
            raise ValueError("Dividend suspension threshold must be positive")

    def __str__(self) -> str:
        """String representation of configuration."""
        return f"""Configuration:
  SATA: {self.sata_shares_outstanding:,} shares @ ${self.sata_par_value:.0f} par ({self.sata_annual_dividend_rate:.2%} yield)
  Treasury: {self.initial_bitcoin_holdings:,.2f} BTC + ${self.initial_cash_reserve:,.0f} cash
  Finance: {self.discount_rate_annual:.2%} annual discount rate
  Suspension: {self.dividend_suspension_threshold_multiplier:.2f}x par value threshold"""

